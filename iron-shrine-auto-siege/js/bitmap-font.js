export function textWidth(text, scale = 1, spacing = 1) {
  let total = 0;
  for (const char of String(text).toUpperCase()) {
    const glyph = GLYPHS[char] || GLYPHS["?"];
    total += (glyph[0].length + spacing) * scale;
  }
  return Math.max(0, total - spacing * scale);
}

export function drawText(ctx, text, x, y, options = {}) {
  const scale = options.scale || 1;
  const spacing = options.spacing ?? 1;
  const value = String(text).toUpperCase();
  const width = textWidth(value, scale, spacing);
  let cursor = options.align === "center" ? Math.round(x - width / 2)
    : options.align === "right" ? Math.round(x - width) : Math.round(x);
  const top = Math.round(y);

  if (options.shadow) {
    drawGlyphRun(ctx, value, cursor + scale, top + scale, scale, spacing, options.shadow);
  }
  drawGlyphRun(ctx, value, cursor, top, scale, spacing, options.color || "#fff");
  return width;
}

export function drawKText(ctx, text, x, y, options = {}) {
  const size = options.size || 8;
  const weight = options.weight || 800;
  ctx.save();
  ctx.font = `${weight} ${size}px "Apple SD Gothic Neo", "Pretendard", "Noto Sans KR", sans-serif`;
  ctx.textAlign = options.align || "left";
  ctx.textBaseline = "top";
  if (options.shadow) {
    ctx.fillStyle = options.shadow;
    ctx.fillText(String(text), Math.round(x) + 1, Math.round(y) + 1);
  }
  ctx.fillStyle = options.color || "#fff";
  ctx.fillText(String(text), Math.round(x), Math.round(y));
  ctx.restore();
}

export function drawHybridText(ctx, text, x, y, options = {}) {
  return /[ㄱ-ㅎㅏ-ㅣ가-힣]/.test(String(text))
    ? drawKText(ctx, text, x, y, options)
    : drawText(ctx, text, x, y, options);
}

function drawGlyphRun(ctx, value, startX, y, scale, spacing, color) {
  let cursor = startX;
  ctx.fillStyle = color;
  for (const char of value) {
    const glyph = GLYPHS[char] || GLYPHS["?"];
    for (let row = 0; row < glyph.length; row++) {
      for (let col = 0; col < glyph[row].length; col++) {
        if (glyph[row][col] === "1") ctx.fillRect(cursor + col * scale, y + row * scale, scale, scale);
      }
    }
    cursor += (glyph[0].length + spacing) * scale;
  }
}
